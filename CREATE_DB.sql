create table public.perfiles (
    id uuid references auth.users on delete cascade primary key,
    nombre text not null,
    carrera text not null,
    tasa_asistencia int2 not null default 100 check (tasa_asistencia >= 0 and tasa_asistencia <= 100),
    reputacion_stars numeric(2,1) not null default 5.0 check (reputacion_stars >= 1.0 and reputacion_stars <= 5.0),
    strikes int2 not null default 0 check (strikes >= 0 and strikes <= 3),
    estado text not null default 'activo' check (estado in ('activo', 'suspendido', 'bloqueado')),
    es_admin boolean not null default false,
    fecha_registro timestamp with time zone default timezone('utc'::text, now()) not null
);

create table public.actividades (
    id bigint generated by default as identity primary key,
    creador_id uuid references public.perfiles(id) on delete cascade not null,
    titulo text not null check (char_length(titulo) >= 5 and char_length(titulo) <= 100),
    categoria text not null check (categoria in ('Deportes', 'Estudio', 'Ocio', 'Proyectos')),
    fecha_hora timestamp with time zone not null,
    duracion_horas int2 not null default 2 check (duracion_horas in (1, 2, 3, 4, 6, 8)), -- Sincronizado con duración numérica de la app
    lugar text not null check (char_length(lugar) >= 3),
    cupos_min int2 not null default 2 check (cupos_min >= 2),
    cupos_max int2 not null check (cupos_max >= 2 and cupos_max <= 30),
    estado text not null default 'abierto' check (estado in ('abierto', 'confirmado', 'finalizado', 'cancelado')),
    recompensa text default 'Gratis' check (char_length(recompensa) <= 150),
    fecha_creacion timestamp with time zone default timezone('utc'::text, now()) not null,
    constraint check_quorum_coherente check (cupos_min <= cupos_max)
);

create table public.participantes (
    id bigint generated by default as identity primary key,
    actividad_id bigint references public.actividades(id) on delete cascade not null,
    usuario_id uuid references public.perfiles(id) on delete cascade not null,
    rol text not null default 'asistente' check (rol in ('organizador', 'asistente')),
    estado_asistencia text not null default 'pendiente' check (estado_asistencia in ('pendiente', 'asistio', 'planton')),
    fecha_union timestamp with time zone default timezone('utc'::text, now()) not null,
    constraint unica_participacion unique (actividad_id, usuario_id)
);

create table public.mensajes (
    id bigint generated by default as identity primary key,
    actividad_id bigint references public.actividades(id) on delete cascade not null,
    usuario_id uuid references public.perfiles(id) on delete cascade not null,
    contenido text not null check (char_length(contenido) >= 1 and char_length(contenido) <= 500),
    fecha_envio timestamp with time zone default timezone('utc'::text, now()) not null
);

create table public.historial_strikes (
    id bigint generated by default as identity primary key,
    usuario_id uuid references public.perfiles(id) on delete cascade not null,
    actividad_id bigint references public.actividades(id) on delete set null,
    motivo text not null check (char_length(motivo) >= 10),
    fecha_emision timestamp with time zone default timezone('utc'::text, now()) not null
);

create table public.reportes_asistencia (
    id bigint generated by default as identity primary key,
    reportante_id uuid references public.perfiles(id) on delete cascade not null,
    reportado_id uuid references public.perfiles(id) on delete cascade not null,
    actividad_id bigint references public.actividades(id) on delete cascade not null,
    detalles text not null check (char_length(detalles) >= 15),
    revisado_por_admin boolean default false not null,
    fecha_reporte timestamp with time zone default timezone('utc'::text, now()) not null,
    constraint unico_reporte_por_evento unique (reportante_id, reportado_id, actividad_id)
);

create table public.calificaciones (
    id bigint generated by default as identity primary key,
    actividad_id bigint references public.actividades(id) on delete cascade not null,
    calificador_id uuid references public.perfiles(id) on delete cascade not null,
    tipo text not null default 'actividad' check (tipo in ('actividad', 'usuario')),
    calificado_id uuid references public.perfiles(id) on delete cascade not null, -- ID del Organizador evaluado
    puntuacion int2 not null check (puntuacion >= 1 and puntuacion <= 3), -- Mapeado del RatingModal de la app
    fecha_creacion timestamp with time zone default timezone('utc'::text, now()) not null,
    constraint unica_calificacion_por_evento unique (actividad_id, calificador_id, tipo)
);

