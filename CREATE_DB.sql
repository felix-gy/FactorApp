-- RPC A: Inscripción Concurrentemente Segura (Bloqueo Pesimista)
create or replace function public.unirse_a_actividad_concurrente(p_actividad_id bigint, p_usuario_id uuid) returns json as $$
declare v_max int2; v_actuales bigint; v_estado text; v_user_estado text;
begin
    select estado into v_user_estado from public.perfiles where id = p_usuario_id;
    if v_user_estado <> 'activo' then return json_build_object('success', false, 'message', 'Cuenta no activa'); end if;

    select cupos_max, estado into v_max, v_estado from public.actividades where id = p_actividad_id for update;
    if v_estado <> 'abierto' then return json_build_object('success', false, 'message', 'Cerrada'); end if;
    
    select count(*) into v_actuales from public.participantes where actividad_id = p_actividad_id;
    if v_actuales >= v_max then return json_build_object('success', false, 'message', 'Llena'); end if;
    
    insert into public.participantes (actividad_id, usuario_id, rol) values (p_actividad_id, p_usuario_id, 'asistente');
    return json_build_object('success', true, 'message', 'Unido');
end; $$ language plpgsql security definer;

-- RPC B: Resolución y Despacho Administrativo de Denuncias
create or replace function public.resolver_reporte_incidencia(p_reporte_id bigint, p_emitir_strike boolean, p_motivo text) returns json as $$
declare v_reportado_id uuid; v_actividad_id bigint;
begin
    if not exists (select 1 from public.perfiles where id = auth.uid() and es_admin = true) then
        return json_build_object('success', false, 'message', 'Acceso denegado: Requiere rol es_admin.');
    end if;

    select reportado_id, actividad_id into v_reportado_id, v_actividad_id from public.reportes_asistencia where id = p_reporte_id;
    if v_reportado_id is null then return json_build_object('success', false, 'message', 'Reporte inexistente'); end if;

    update public.reportes_asistencia set revisado_por_admin = true where id = p_reporte_id;

    if p_emitir_strike = true then
        insert into public.historial_strikes (usuario_id, actividad_id, motivo)
        values (v_reportado_id, v_actividad_id, coalesce(p_motivo, 'Falta comunitaria validada por administración.'));
    end if;

    return json_build_object('success', true, 'message', 'Resolución procesada de forma consistente.');
end; $$ language plpgsql security definer;

