create policy "Permitir calificar" on public.calificaciones for insert with check (auth.uid() = calificador_id);
create policy "Ver calificaciones" on public.calificaciones for select using (auth.role() = 'authenticated');

create policy "Ver propios strikes" on public.historial_strikes for select using (auth.uid() = usuario_id);
create policy "Insertar reportes" on public.reportes_asistencia for insert with check (auth.uid() = reportante_id);
create policy "Ver propios reportes" on public.reportes_asistencia for select using (auth.uid() = reportante_id or auth.uid() = reportado_id);

create policy "Leer chat" on public.mensajes for select using (
    (select estado from public.perfiles where id = auth.uid()) = 'activo'
    and exists (select 1 from public.participantes where participantes.actividad_id = mensajes.actividad_id and participantes.usuario_id = auth.uid())
);

create policy "Escribir en chat" on public.mensajes for insert with check (
    auth.uid() = usuario_id 
    and (select estado from public.perfiles where id = auth.uid()) = 'activo'
    and exists (select 1 from public.participantes where participantes.actividad_id = mensajes.actividad_id and participantes.usuario_id = auth.uid())
);

