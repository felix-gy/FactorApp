-- TRIGGER 1: Registro Exclusivo UCSP
create or replace function public.crear_perfil_nuevo_usuario() returns trigger as $$
begin
    if lower(new.email) not like '%@ucsp.edu.pe' then raise exception 'Solo correos @ucsp.edu.pe'; end if;
    insert into public.perfiles (id, nombre, carrera) values (new.id, coalesce(new.raw_user_meta_data->>'nombre', 'Estudiante UCSP'), coalesce(new.raw_user_meta_data->>'carrera', 'Por Definir'));
    return new;
end; $$ language plpgsql security definer;
create trigger tr_crear_perfil_nuevo_usuario after insert on auth.users for each row execute function public.crear_perfil_nuevo_usuario();

-- TRIGGER 2: Auto-matricular Organizador
create or replace function public.auto_agregar_organizador() returns trigger as $$
begin
    insert into public.participantes (actividad_id, usuario_id, rol, estado_asistencia) values (new.id, new.creador_id, 'organizador', 'asistio');
    return new;
end; $$ language plpgsql security definer;
create trigger tr_auto_agregar_organizador after insert on public.actividades for each row execute function public.auto_agregar_organizador();

-- TRIGGER 3: Procesamiento Analítico de Tasa de Asistencia
create or replace function public.actualizar_tasa_asistencia() returns trigger as $$
declare v_total int; v_asistencias int; v_tasa int2;
begin
    select count(*) into v_total from public.participantes where usuario_id = new.usuario_id and estado_asistencia in ('asistio', 'planton');
    select count(*) into v_asistencias from public.participantes where usuario_id = new.usuario_id and estado_asistencia = 'asistio';
    if v_total > 0 then v_tasa := round((v_asistencias::numeric / v_total::numeric) * 100); else v_tasa := 100; end if;
    update public.perfiles set tasa_asistencia = v_tasa where id = new.usuario_id;
    return new;
end; $$ language plpgsql security definer;
create trigger tr_actualizar_tasa_asistencia after update of estado_asistencia on public.participantes for each row when (new.estado_asistencia in ('asistio', 'planton')) execute function public.actualizar_tasa_asistencia();

-- TRIGGER 4: Conversión de Reputación Decimal a Escala de Estrellas (1.0 - 5.0)
create or replace function public.actualizar_reputacion_organizador() returns trigger as $$
declare v_promedio numeric; v_estrellas numeric(2,1);
begin
    select avg(puntuacion) into v_promedio from public.calificaciones where calificado_id = new.calificado_id and tipo = 'actividad';
    if v_promedio is not null then v_estrellas := round((((v_promedio - 1.0) / 2.0) * 4.0 + 1.0)::numeric, 1); else v_estrellas := 5.0; end if;
    update public.perfiles set reputacion_stars = v_estrellas where id = new.calificado_id;
    return new;
end; $$ language plpgsql security definer;
create trigger tr_actualizar_reputacion_organizador after insert or update on public.calificaciones for each row execute function public.actualizar_reputacion_organizador();

-- TRIGGER 5: Auditoría y Baneo Automático por Acumulación de Strikes
create or replace function public.procesar_y_banear_usuario() returns trigger as $$
declare v_total_strikes int2;
begin
    select count(*)::int2 into v_total_strikes from public.historial_strikes where usuario_id = new.usuario_id;
    update public.perfiles set strikes = v_total_strikes where id = new.usuario_id;
    if v_total_strikes >= 3 then
        update public.perfiles set estado = 'bloqueado' where id = new.usuario_id;
    end if;
    return new;
end; $$ language plpgsql security definer;
create trigger tr_procesar_y_banear_usuario after insert on public.historial_strikes for each row execute function public.procesar_y_banear_usuario();

