create or replace view public.panel_administrador_alertas as
select 
    r.id as reporte_id,
    r.fecha_reporte,
    act.titulo as actividad_titulo,
    act.estado as actividad_estado,
    (select count(*) from public.participantes p where p.actividad_id = act.id) as total_asistentes,
    perf_nte.nombre as reportante_nombre,
    perf_do.nombre as reportado_nombre,
    perf_do.strikes as reportado_strikes_actuales,
    perf_do.estado as reportado_estado_cuenta,
    r.detalles as motivo_reporte,
    r.revisado_por_admin
from public.reportes_asistencia r
join public.actividades act on r.actividad_id = act.id
join public.perfiles perf_nte on r.reportante_id = perf_nte.id
join public.perfiles perf_do on r.reportado_id = perf_do.id;

alter view public.panel_administrador_alertas owner to postgres;
create policy "Vista de alertas para admins" on public.reportes_asistencia for select using ((select es_admin from public.perfiles where id = auth.uid()) = true);